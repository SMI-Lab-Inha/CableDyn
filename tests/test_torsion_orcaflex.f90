!> Torsion compared with OrcaFlex 11.6d summary values (tests/data/torsion_orcaflex_refs.txt,
!> regenerated by validation/scripts/orcaflex_torsion_reference.py):
!>  a. pure torsion of a straight clamped line through the deck (L 10 m, GJ 10 kN.m^2): the
!>     torque at End A and End B for gamma_B = 90, 450, 1800 and -90 deg, gamma_A 30 / gamma_B
!>     120 deg (only the difference matters), and two sections in series (GJ 10 / 25 kN.m^2);
!>  b. Greenhill onset of the clamped-clamped line at T L^2/EI = 0, 10, 50 and 200, and of
!>     bending-pinned, torsion-restrained ends at 0 and 10 (the semi-tangential end), N = 32,
!>     against OrcaFlex extrapolated to zero segment length;
!>  c. the Lozon et al. (2025) Gulf of Mexico 80 m lazy-wave cable with an illustrative
!>     GJ = 50 kN.m^2, clamped at both ends in its untwisted static orientation and twisted
!>     0 to 5 turns at the hang-off through the deck Pretwist: hang-off torque, geometric twist
!>     Theta = Phi - M L / GJ, peak interior curvature, out-of-plane offset and hang-off tension;
!>     at zero twist the deck also reproduces the same cable without torsion columns.
!> Argument 1: tests/data/torsion_orcaflex_refs.txt.
PROGRAM test_torsion_orcaflex
  USE CableDyn_Precision, ONLY: wp
  USE CableDyn_DeckDriver, ONLY: CD_Run_Deck_Driver, CD_DECKDRV_OK
  USE CableDyn_HermiteCableStatic, ONLY: CD_HermiteCable_Static_Solve, CD_HCSTAT_OK
  USE CableDyn_HermiteTorsion, ONLY: CD_HermiteTorsionType
  USE CableDyn_EndConnection, ONLY: CD_ENDCONN_PINNED, CD_ENDCONN_RIGID
  USE, INTRINSIC :: IEEE_ARITHMETIC, ONLY: IEEE_IS_FINITE
  IMPLICIT NONE

  REAL(wp), PARAMETER :: PI = 3.14159265358979323846_wp, RHOW = 1025.0_wp
  INTEGER :: n_fail = 0, npure = 0, nclamp = 0, npin = 0, nlw = 0
  REAL(wp) :: pure(3, 8), series_ref = 0.0_wp, clamp(3, 8), pin(3, 4), orient(2) = 0.0_wp, lw(6, 8)
  CHARACTER(512) :: ref_path

  IF (COMMAND_ARGUMENT_COUNT() < 1) THEN
    WRITE (*, '(A)') 'usage: test_torsion_orcaflex <torsion_orcaflex_refs.txt>'
    ERROR STOP 2
  END IF
  CALL GET_COMMAND_ARGUMENT(1, ref_path)
  CALL read_refs()

  CALL check_pure()
  CALL check_onsets()
  CALL check_lazy_wave()

  IF (n_fail > 0) THEN
    WRITE (*, '(A,I0,A)') 'FAIL: ', n_fail, ' torsion OrcaFlex comparison(s) failed'
    ERROR STOP 1
  END IF
  WRITE (*, '(A)') 'PASS: torsion agrees with the OrcaFlex 11.6d summary values'

CONTAINS

  INCLUDE 'nan_max_abs.inc'

  SUBROUTINE require(cond, msg)
    LOGICAL, INTENT(IN) :: cond
    CHARACTER(*), INTENT(IN) :: msg
    IF (.NOT. cond) THEN
      n_fail = n_fail + 1
      WRITE (*, '(A,A)') 'FAILED: ', msg
    END IF
  END SUBROUTINE require

  SUBROUTINE read_refs()
    INTEGER :: u, ios
    CHARACTER(512) :: line
    CHARACTER(16) :: tag
    REAL(wp) :: v(6)
    OPEN (NEWUNIT=u, FILE=ref_path, STATUS='OLD', ACTION='READ', IOSTAT=ios)
    IF (ios /= 0) THEN
      WRITE (*, '(A)') 'cannot open '//TRIM(ref_path)
      ERROR STOP 2
    END IF
    DO
      READ (u, '(A)', IOSTAT=ios) line
      IF (ios /= 0) EXIT
      IF (LEN_TRIM(line) == 0 .OR. line(1:1) == '#') CYCLE
      READ (line, *, IOSTAT=ios) tag
      IF (ios /= 0) CYCLE
      v = 0.0_wp
      SELECT CASE (TRIM(tag))
      CASE ('pure')
        READ (line, *, IOSTAT=ios) tag, v(1:3)
        IF (ios == 0 .AND. npure < SIZE(pure, 2)) THEN
          npure = npure + 1
          pure(:, npure) = v(1:3)
        END IF
      CASE ('series')
        READ (line, *, IOSTAT=ios) tag, series_ref
      CASE ('clamped')
        READ (line, *, IOSTAT=ios) tag, v(1:3)
        IF (ios == 0 .AND. nclamp < SIZE(clamp, 2)) THEN
          nclamp = nclamp + 1
          clamp(:, nclamp) = v(1:3)
        END IF
      CASE ('pinned')
        READ (line, *, IOSTAT=ios) tag, v(1:3)
        IF (ios == 0 .AND. npin < SIZE(pin, 2)) THEN
          npin = npin + 1
          pin(:, npin) = v(1:3)
        END IF
      CASE ('orientation')
        READ (line, *, IOSTAT=ios) tag, orient
      CASE ('lazywave')
        READ (line, *, IOSTAT=ios) tag, v
        IF (ios == 0 .AND. nlw < SIZE(lw, 2)) THEN
          nlw = nlw + 1
          lw(:, nlw) = v
        END IF
      END SELECT
    END DO
    CLOSE (u)
    IF (npure < 5 .OR. nclamp < 4 .OR. npin < 2 .OR. nlw < 6 .OR. series_ref <= 0.0_wp .OR. orient(1) <= 0.0_wp) THEN
      WRITE (*, '(A)') 'reference file incomplete: '//TRIM(ref_path)
      ERROR STOP 2
    END IF
  END SUBROUTINE read_refs

  SUBROUTINE write_deck(path, types, points, sections, endconns, options, outs)
    !! A one-line deck: line 1 from point 1 (End A) to point 2 (End B).
    CHARACTER(*), INTENT(IN) :: path, types(:), points(:), sections(:), endconns(:), options(:), outs(:)
    INTEGER :: u, i
    OPEN (NEWUNIT=u, FILE=path, STATUS='REPLACE', ACTION='WRITE')
    WRITE (u, '(A)') 'torsion OrcaFlex comparison deck'
    WRITE (u, '(A)') '--- LINE TYPES ---'
    WRITE (u, '(A)') 'Name Diam Mass EA BA EI GAs GJ Irt Irn Cdn Cdt Can Cat'
    WRITE (u, '(A)') '(-) (m) (kg/m) (N) (-) (Nm2) (N) (Nm2) (kgm) (kgm) (-) (-) (-) (-)'
    DO i = 1, SIZE(types)
      WRITE (u, '(A)') TRIM(types(i))
    END DO
    WRITE (u, '(A)') '--- POINTS ---'
    WRITE (u, '(A)') 'ID Type X Y Z Mass Vol CdA Ca'
    WRITE (u, '(A)') '(-) (-) (m) (m) (m) (kg) (m3) (m2) (-)'
    DO i = 1, SIZE(points)
      WRITE (u, '(A)') TRIM(points(i))
    END DO
    WRITE (u, '(A)') '--- LINES ---'
    WRITE (u, '(A)') 'ID NodeA NodeB Outputs'
    WRITE (u, '(A)') '(-) (-) (-) (-)'
    WRITE (u, '(A)') '1 1 2 -'
    WRITE (u, '(A)') '--- SECTIONS ---'
    WRITE (u, '(A)') 'LineID LineType Length NumSegs'
    WRITE (u, '(A)') '(-) (-) (m) (-)'
    DO i = 1, SIZE(sections)
      WRITE (u, '(A)') TRIM(sections(i))
    END DO
    WRITE (u, '(A)') '--- END CONNECTIONS ---'
    WRITE (u, '(A)') 'LineID End Stiffness EzX EzY EzZ TorsStiffness NxX NxY NxZ Pretwist'
    WRITE (u, '(A)') '(-) (-) (N-m/rad) (-) (-) (-) (N-m/rad) (-) (-) (-) (deg)'
    DO i = 1, SIZE(endconns)
      WRITE (u, '(A)') TRIM(endconns(i))
    END DO
    WRITE (u, '(A)') '--- OPTIONS ---'
    WRITE (u, '(A)') '9.80665 g'
    WRITE (u, '(A)') '1025.0 rhoW'
    DO i = 1, SIZE(options)
      WRITE (u, '(A)') TRIM(options(i))
    END DO
    WRITE (u, '(A)') '--- OUTPUTS ---'
    DO i = 1, SIZE(outs)
      WRITE (u, '(A)') TRIM(outs(i))
    END DO
    WRITE (u, '(A)') '--- END ---'
    CLOSE (u)
  END SUBROUTINE write_deck

  SUBROUTINE run_deck(path, root, ok, em_out)
    CHARACTER(*), INTENT(IN) :: path, root
    LOGICAL, INTENT(OUT) :: ok
    CHARACTER(*), INTENT(OUT) :: em_out
    LOGICAL :: conv
    INTEGER :: es
    CALL CD_Run_Deck_Driver(path, root, conv, es, em_out)
    ok = es == CD_DECKDRV_OK .AND. conv
  END SUBROUTINE run_deck

  SUBROUTINE read_row(path, vals, ok)
    !! The first data row of a driver .out file.
    CHARACTER(*), INTENT(IN) :: path
    REAL(wp), INTENT(OUT) :: vals(:)
    LOGICAL, INTENT(OUT) :: ok
    INTEGER :: u, ios
    CHARACTER(2048) :: buf
    ok = .FALSE.
    vals = 0.0_wp
    OPEN (NEWUNIT=u, FILE=path, STATUS='OLD', ACTION='READ', IOSTAT=ios)
    IF (ios /= 0) RETURN
    READ (u, '(A)', IOSTAT=ios) buf
    READ (u, '(A)', IOSTAT=ios) buf
    READ (u, *, IOSTAT=ios) vals
    CLOSE (u)
    ok = ios == 0 .AND. ALL(IEEE_IS_FINITE(vals))
  END SUBROUTINE read_row

  SUBROUTINE read_profile(path, prof, n, ok)
    !! The rows of a .static.out file: LineID Node ArcLength X Y Z Tension Curvature BendMoment
    !! Declination Inclination Azimuth (prof(1:12, 1:n)).
    CHARACTER(*), INTENT(IN) :: path
    REAL(wp), ALLOCATABLE, INTENT(OUT) :: prof(:, :)
    INTEGER, INTENT(OUT) :: n
    LOGICAL, INTENT(OUT) :: ok
    INTEGER :: u, ios
    REAL(wp) :: row(12)
    CHARACTER(2048) :: buf
    ALLOCATE (prof(12, 4096))
    n = 0
    ok = .FALSE.
    OPEN (NEWUNIT=u, FILE=path, STATUS='OLD', ACTION='READ', IOSTAT=ios)
    IF (ios /= 0) RETURN
    READ (u, '(A)', IOSTAT=ios) buf
    READ (u, '(A)', IOSTAT=ios) buf
    READ (u, '(A)', IOSTAT=ios) buf
    DO
      READ (u, *, IOSTAT=ios) row
      IF (ios /= 0) EXIT
      IF (n >= SIZE(prof, 2)) EXIT
      n = n + 1
      prof(:, n) = row
    END DO
    CLOSE (u)
    ok = n > 0 .AND. ALL(IEEE_IS_FINITE(prof(:, 1:n)))
  END SUBROUTINE read_profile

