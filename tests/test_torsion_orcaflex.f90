  SUBROUTINE check_pure()
    !! a. Straight neutral 0.1 m line along +x, End A Coupled at x = 0, End B Fixed at x = 10,
    !!    20 elements, EA 1e8 N, GJ 1e4 N.m^2, both ends clamped and restrained in torsion with
    !!    the pretwists gamma_A and gamma_B. Output precision is 8 digits. OrcaFlex's EI of
    !!    1 kN.m^2 puts every case but -90/90 deg above the Greenhill onset (0.90 kN.m): OrcaFlex
    !!    statics stays on the straight branch there, whereas CableDyn's stability check leaves
    !!    it for the buckled shape. The torque of the straight branch does not depend on EI, so
    !!    the deck uses EI = 1e6 N.m^2, which keeps the straight line stable up to five turns.
    CHARACTER(160) :: t(2), ec(2)
    CHARACTER(24) :: secs(2)
    REAL(wp) :: v(3), mass, err
    LOGICAL :: ok
    CHARACTER(512) :: em
    INTEGER :: k, ns
    mass = RHOW*0.25_wp*PI*0.01_wp
    WRITE (t(1), '(A,ES24.16,A)') 'rodA 0.1 ', mass, ' 1.0e8 0.0 1.0e6 1.0e8 1.0e4 1.0 1.0 0 0 0 0'
    WRITE (t(2), '(A,ES24.16,A)') 'rodB 0.1 ', mass, ' 1.0e8 0.0 1.0e6 1.0e8 2.5e4 1.0 1.0 0 0 0 0'
    DO k = 1, npure + 1
      IF (k <= npure) THEN
        WRITE (ec(1), '(A,F10.3)') '1 A Rigid 1 0 0 Rigid 0 0 1 ', pure(1, k)
        WRITE (ec(2), '(A,F10.3)') '1 B Rigid 1 0 0 Rigid 0 0 1 ', pure(2, k)
        secs(1) = '1 rodA 10.0 20'
        ns = 1
      ELSE
        ec(1) = '1 A Rigid 1 0 0 Rigid 0 0 1 0'
        ec(2) = '1 B Rigid 1 0 0 Rigid 0 0 1 90'
        secs(1) = '1 rodA 4.0 8'
        secs(2) = '1 rodB 6.0 12'
        ns = 2
      END IF
      CALL write_deck('tofx_pure.dat', t, [CHARACTER(48) :: '1 Coupled 0.0 0.0 -50.0 0 0 0 0', &
                                           '2 Fixed 10.0 0.0 -50.0 0 0 0 0'], secs(1:ns), ec, &
                      [CHARACTER(24) :: '0.1 dtM', '0.0 TMax'], [CHARACTER(16) :: 'Torq1N1', 'Torq1N21'])
      CALL run_deck('tofx_pure.dat', 'tofx_pure', ok, em)
      CALL require(ok, 'a: pure torsion deck runs: '//TRIM(em))
      IF (.NOT. ok) CYCLE
      CALL read_row('tofx_pure.out', v, ok)
      CALL require(ok, 'a: output readable')
      IF (k <= npure) THEN
        err = nan_max_abs(v(2:3) - pure(3, k))/ABS(pure(3, k))
        WRITE (*, '(A,2F8.1,A,2ES16.8,A,ES16.8,A,ES9.2)') 'a: gamma_A, gamma_B ', pure(1:2, k), ' deg: Torq ', &
          v(2:3), ' OrcaFlex ', pure(3, k), ' rel. ', err
      ELSE
        err = nan_max_abs(v(2:3) - series_ref)/series_ref
        WRITE (*, '(A,2ES16.8,A,ES16.8,A,ES9.2)') 'a: two sections in series: Torq ', v(2:3), ' OrcaFlex ', &
          series_ref, ' rel. ', err
      END IF
      CALL require(err <= 1.0e-7_wp, 'a: torque equals OrcaFlex to output precision')
    END DO
  END SUBROUTINE check_pure

  ! ------------------------------------------------------------------------------------------
  SUBROUTINE check_onsets()
    !! b. EI = L = GJ = 1, EA = 1e7 (EA L^2/EI of the OrcaFlex model), N = 32; onset bisected on
    !!    the stability report of the straight state (sliding End B under the dead tension). Compared with OrcaFlex
    !!    extrapolated to zero segment length (its 200-segment value is listed alongside).
    REAL(wp) :: m, err, err200
    INTEGER :: k
    DO k = 1, nclamp
      m = onset(32, clamp(1, k), CD_ENDCONN_RIGID, clamp(3, k))
      err = (m - clamp(3, k))/clamp(3, k)
      err200 = (clamp(2, k) - clamp(3, k))/clamp(3, k)
      WRITE (*, '(A,F6.1,A,F12.7,A,F12.7,A,ES10.2,A,ES10.2,A)') 'b: clamped T L^2/EI = ', clamp(1, k), &
        ': CableDyn (N = 32) ', m, ', OrcaFlex extrapolated ', clamp(3, k), ', rel. ', err, &
        ' (OrcaFlex 200 segments ', err200, ')'
      CALL require(m > 0.0_wp .AND. ABS(err) <= 2.0e-4_wp, 'b: clamped onset within 2e-4 of OrcaFlex extrapolated')
    END DO
    DO k = 1, npin
      m = onset(32, pin(1, k), CD_ENDCONN_PINNED, pin(3, k))
      err = (m - pin(3, k))/pin(3, k)
      err200 = (pin(2, k) - pin(3, k))/pin(3, k)
      WRITE (*, '(A,F6.1,A,F12.7,A,F12.7,A,ES10.2,A,ES10.2,A)') 'b: pinned (semi-tangential) T L^2/EI = ', &
        pin(1, k), ': CableDyn (N = 32) ', m, ', OrcaFlex extrapolated ', pin(3, k), ', rel. ', err, &
        ' (OrcaFlex 200 segments ', err200, ')'
      CALL require(m > 0.0_wp .AND. ABS(err) <= 2.0e-4_wp, 'b: pinned onset within 2e-4 of OrcaFlex extrapolated')
    END DO
  END SUBROUTINE check_onsets

  REAL(wp) FUNCTION onset(ne, tension, mode, mguess) RESULT(mcr)
    INTEGER, INTENT(IN) :: ne, mode
    REAL(wp), INTENT(IN) :: tension, mguess
    REAL(wp) :: lo, hi, mid
    INTEGER :: k
    LOGICAL :: failed
    lo = 0.9_wp*mguess
    hi = 1.1_wp*mguess
    mcr = -1.0_wp
    IF (.NOT. stable_at(ne, tension, mode, lo, failed)) RETURN
    IF (stable_at(ne, tension, mode, hi, failed)) RETURN
    DO k = 1, 60
      mid = 0.5_wp*(lo + hi)
      IF (stable_at(ne, tension, mode, mid, failed)) THEN
        lo = mid
      ELSE
        hi = mid
      END IF
      IF (failed) RETURN
      IF (hi - lo <= 1.0e-8_wp*mguess) EXIT
    END DO
    mcr = 0.5_wp*(lo + hi)
  END FUNCTION onset

  LOGICAL FUNCTION stable_at(ne, tension, mode, m, failed) RESULT(stab)
    INTEGER, INTENT(IN) :: ne, mode
    REAL(wp), INTENT(IN) :: tension, m
    LOGICAL, INTENT(OUT) :: failed
    TYPE(CD_HermiteTorsionType) :: tors
    REAL(wp), ALLOCATABLE :: seed(:), l0(:), q(:), f(:), curv(:)
    REAL(wp) :: res
    INTEGER :: nd, it, es, k
    CHARACTER(512) :: em
    nd = 6*(ne + 1)
    ALLOCATE (seed(nd), l0(ne), q(nd), f(nd), curv(ne + 1))
    l0 = 1.0_wp/ne
    seed = 0.0_wp
    DO k = 0, ne
      seed(6*k + 1) = REAL(k, wp)/ne
      seed(6*k + 4) = 1.0_wp
    END DO
    f = 0.0_wp
    f(nd - 5) = tension
    tors%active = .TRUE.
    ALLOCATE (tors%gj(ne))
    tors%gj = 1.0_wp
    tors%phi = m
    tors%ends = RESHAPE([1.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 0.0_wp, 1.0_wp, 1.0_wp, 0.0_wp, 0.0_wp, &
                         0.0_wp, 0.0_wp, 1.0_wp], [3, 4])
    tors%descend = .FALSE.
    CALL CD_HermiteCable_Static_Solve(l0, [(1.0e7_wp, it=1, ne)], [(1.0_wp, it=1, ne)], [(0.0_wp, it=1, ne)], seed, &
                                      [1, 2, 3, nd - 4, nd - 3], -1.0e6_wp, 0.0_wp, 1, 60, 1.0e-7_wp, 1.0_wp, q, &
                                      curv, res, it, es, em, f_nodal=f, endconn_stiffness=[0.0_wp, 0.0_wp], &
                                      endconn_direction=RESHAPE([1.0_wp, 0.0_wp, 0.0_wp, 1.0_wp, 0.0_wp, 0.0_wp], &
                                                                [3, 2]), &
                                      endconn_mode=[mode, mode], torsion=tors)
    failed = es /= CD_HCSTAT_OK
    IF (failed) WRITE (*, '(A)') '  solve failed: '//TRIM(em)
    stab = tors%stable .AND. .NOT. failed
  END FUNCTION stable_at

