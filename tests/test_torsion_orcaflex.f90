  SUBROUTINE lazy_wave_deck(path, turns, with_torsion)
    !! The Gulf of Mexico 80 m cable of the OrcaFlex case, hang-off End A (Coupled, held) and
    !! anchor End B (Fixed), 0.375 m elements, both ends Rigid along the untwisted OrcaFlex end
    !! orientation (End A to End B), reference normals +y, the twist at the hang-off. OrcaFlex
    !! twists its End B (the hang-off) by gamma_B = +turns about its A->B tangent; here the
    !! hang-off is End A and its Ez points the other way, so Pretwist(A) = -360 turns and
    !! Phi = Pretwist(B) - Pretwist(A) = +360 turns: the same physical twist and torque sign.
    CHARACTER(*), INTENT(IN) :: path
    REAL(wp), INTENT(IN) :: turns
    LOGICAL, INTENT(IN) :: with_torsion
    REAL(wp) :: da, db
    CHARACTER(200) :: t(2), ec(2)
    da = orient(2)*PI/180.0_wp
    db = orient(1)*PI/180.0_wp
    ! bare 0.16 m, 36.7 kg/m; buoyancy section 0.29 m, 59.53 kg/m; EA 469 MN, EI 19.9 kN.m^2,
    ! GJ 50 kN.m^2; GAs and the rotary inertias of the circular-section closure (not used here)
    t(1) = 'bare 0.160 36.70 4.69e8 0.0 1.99e4 9.0192e7 5.0e4 0.058720 0.117440 1.2 0.1 1.0 0.0'
    t(2) = 'buoy 0.290 59.53 4.69e8 0.0 1.99e4 9.0192e7 5.0e4 0.312904 0.625808 1.2 0.1 1.0 0.0'
    IF (with_torsion) THEN
      WRITE (ec(1), '(A,ES24.16,A,ES24.16,A,F10.2)') '1 A Rigid ', SIN(da), ' 0.0 ', -COS(da), ' Rigid 0 1 0 ', &
        -360.0_wp*turns
      WRITE (ec(2), '(A,ES24.16,A,ES24.16,A)') '1 B Rigid ', SIN(db), ' 0.0 ', -COS(db), ' Rigid 0 1 0 0'
    ELSE
      WRITE (ec(1), '(A,ES24.16,A,ES24.16)') '1 A Rigid ', SIN(da), ' 0.0 ', -COS(da)
      WRITE (ec(2), '(A,ES24.16,A,ES24.16)') '1 B Rigid ', SIN(db), ' 0.0 ', -COS(db)
    END IF
    CALL write_deck(path, t, [CHARACTER(48) :: '1 Coupled 5.0 0.0 -14.0 0 0 0 0', '2 Fixed 125.0 0.0 -80.0 0 0 0 0'], &
                    [CHARACTER(24) :: '1 bare 68.114 182', '1 buoy 50.0 133', '1 bare 52.101 139'], ec, &
                    [CHARACTER(24) :: '80.0 WtrDpth', '1.0e5 kBot', '1.0e4 cBot', '0.05 dtM', '0.0 TMax'], &
                    [CHARACTER(16) :: 'FairTen1'])
    IF (with_torsion) CALL add_outputs(path)
  END SUBROUTINE lazy_wave_deck

  SUBROUTINE add_outputs(path)
    !! Append the torsion channels to the OUTPUTS of a deck written by write_deck.
    CHARACTER(*), INTENT(IN) :: path
    CHARACTER(512) :: lines(200)
    INTEGER :: u, n, ios, k
    OPEN (NEWUNIT=u, FILE=path, STATUS='OLD', ACTION='READ')
    n = 0
    DO
      READ (u, '(A)', IOSTAT=ios) lines(n + 1)
      IF (ios /= 0) EXIT
      n = n + 1
    END DO
    CLOSE (u)
    OPEN (NEWUNIT=u, FILE=path, STATUS='REPLACE', ACTION='WRITE')
    DO k = 1, n
      IF (TRIM(lines(k)) == '--- END ---') THEN
        WRITE (u, '(A)') 'Torq1N1'
        WRITE (u, '(A)') 'Torq1N455'
        WRITE (u, '(A)') 'Twist1'
      END IF
      WRITE (u, '(A)') TRIM(lines(k))
    END DO
    CLOSE (u)
  END SUBROUTINE add_outputs

  SUBROUTINE check_lazy_wave()
    REAL(wp), ALLOCATABLE :: p0(:, :), p1(:, :)
    REAL(wp) :: v(5), tq, th, kap, ymax, ten, etq, eth, ekap, ey, eten, dpos, dten, worst(5)
    INTEGER :: k, n0, n1, jlo, jhi
    LOGICAL :: ok
    CHARACTER(512) :: em
    CHARACTER(32) :: root
    ! zero twist: the same cable without torsion columns (V3 on the lazy wave)
    CALL lazy_wave_deck('tofx_lw_ref.dat', 0.0_wp, .FALSE.)
    CALL run_deck('tofx_lw_ref.dat', 'tofx_lw_ref', ok, em)
    CALL require(ok, 'c: the cable without torsion runs: '//TRIM(em))
    IF (.NOT. ok) RETURN
    CALL read_profile('tofx_lw_ref.static.out', p0, n0, ok)
    CALL require(ok .AND. n0 == 455, 'c: profile without torsion readable')
    worst = 0.0_wp
    DO k = 1, nlw
      WRITE (root, '(A,I0)') 'tofx_lw', k
      CALL lazy_wave_deck(TRIM(root)//'.dat', lw(1, k), .TRUE.)
      CALL run_deck(TRIM(root)//'.dat', TRIM(root), ok, em)
      CALL require(ok, 'c: twisted lazy-wave deck runs: '//TRIM(em))
      IF (.NOT. ok) CYCLE
      CALL read_row(TRIM(root)//'.out', v, ok)
      CALL read_profile(TRIM(root)//'.static.out', p1, n1, ok)
      CALL require(ok .AND. n1 == 455, 'c: outputs readable')
      IF (.NOT. ok) CYCLE
      tq = v(3)
      th = lw(1, k) - v(5)/360.0_wp
      jlo = 1 + NINT(0.03_wp*454)
      jhi = 1 + NINT(0.97_wp*454)
      kap = MAXVAL(p1(8, jlo:jhi))
      ymax = nan_max_abs(p1(5, 1:n1))
      ten = p1(7, 1)
      IF (lw(1, k) < 0.5_wp) THEN
        etq = ABS(tq)
        eth = ABS(th)
        dpos = nan_max_abs(p1(4:6, 1:n1) - p0(4:6, 1:n0))
        dten = nan_max_abs(p1(7, 1:n1) - p0(7, 1:n0))/MAXVAL(p0(7, 1:n0))
        WRITE (*, '(A,ES10.3,A,ES10.3,A,ES10.3,A,ES10.3)') 'c: 0 turns: torque ', tq, ' N m, Theta ', th, &
          ' turns; vs no torsion columns: position ', dpos, ' m, tension ', dten
        CALL require(etq <= 1.0e-6_wp .AND. eth <= 1.0e-9_wp, 'c: no torque and no twist at zero pretwist')
        CALL require(dpos <= 1.0e-6_wp .AND. dten <= 1.0e-6_wp, 'c: zero twist reproduces the cable without torsion')
      ELSE
        etq = ABS(tq/lw(2, k) - 1.0_wp)
        eth = ABS(th - lw(3, k))/lw(1, k)
        worst(1) = nan_max_abs([worst(1), etq])
        worst(2) = nan_max_abs([worst(2), eth])
      END IF
      ekap = ABS(kap/lw(4, k) - 1.0_wp)
      ey = ABS(ymax - lw(5, k))
      eten = ABS(ten/lw(6, k) - 1.0_wp)
      worst(3) = nan_max_abs([worst(3), ekap])
      worst(4) = nan_max_abs([worst(4), ey])
      worst(5) = nan_max_abs([worst(5), eten])
      WRITE (*, '(A,F4.1,A,2F11.3,A,2F9.5,A,2F9.6,A,2F7.3,A,2F10.1)') 'c: turns ', lw(1, k), &
        ': torque (CableDyn, OrcaFlex) ', tq, lw(2, k), ' N m; Theta ', th, lw(3, k), ' turns; peak curvature ', &
        kap, lw(4, k), ' 1/m; max|Y| ', ymax, lw(5, k), ' m; hang-off tension ', ten, lw(6, k)
      CALL require(ABS(v(3) - v(4)) <= 1.0e-6_wp*MAX(1.0_wp, ABS(v(3))), 'c: torque uniform (End A = End B)')
      IF (lw(1, k) > 0.5_wp) THEN
        CALL require(etq <= 1.0e-2_wp, 'c: hang-off torque within 1 % of OrcaFlex')
        CALL require(eth <= 1.0e-3_wp, 'c: geometric twist Theta within 1e-3 turn per imposed turn')
      END IF
      CALL require(ekap <= 1.0e-2_wp, 'c: peak interior curvature within 1 % of OrcaFlex')
      CALL require(ey <= 0.1_wp, 'c: out-of-plane offset within 0.1 m of OrcaFlex')
      CALL require(eten <= 5.0e-3_wp, 'c: hang-off tension within 0.5 % of OrcaFlex')
    END DO
    WRITE (*, '(A,ES9.2,A,ES9.2,A,ES9.2,A,F6.3,A,ES9.2)') 'c: largest differences: torque ', worst(1), &
      ', Theta per turn ', worst(2), ', peak curvature ', worst(3), ', max|Y| ', worst(4), ' m, hang-off tension ', &
      worst(5)
  END SUBROUTINE check_lazy_wave

