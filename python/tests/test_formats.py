# An OutList that requests TwrBsFzt twice, as the r-test IEA-15MW ElastoDyn file does, and
# already uses the suffix the second repeat would take.
OPENFAST_REPEATED = (
    "Predictions were generated by OpenFAST\n"
    "\n"
    "Time\tTwrBsFzt\tRotSpeed\tTwrBsFzt\tTwrBsFzt_3\tTwrBsFzt\n"
    "(s)\t(kN)\t(rpm)\t(kN)\t(kN)\t(kN)\n"
    "0.0\t-1.0\t5.0\t-2.0\t-3.0\t-4.0\n"
    "0.1\t-1.5\t5.1\t-2.5\t-3.5\t-4.5\n"
)


def test_openfast_text_output_keeps_repeated_channels(tmp_path):
    path = tmp_path / "repeat.out"
    path.write_text(OPENFAST_REPEATED, encoding="utf-8")
    with pytest.warns(UserWarning, match=r"repeat\.out:3: .*TwrBsFzt -> TwrBsFzt_2") as caught:
        table = read_openfast_output(path)
    assert len(caught) == 1
    assert "TwrBsFzt -> TwrBsFzt_4" in str(caught[0].message)
    assert table.channels == (
        "Time",
        "TwrBsFzt",
        "RotSpeed",
        "TwrBsFzt_2",
        "TwrBsFzt_3",
        "TwrBsFzt_4",
    )
    assert np.array_equal(table.column("TwrBsFzt"), [-1.0, -1.5])  # first occurrence
    assert np.array_equal(table.column("TwrBsFzt_2"), [-2.0, -2.5])
    assert np.array_equal(table.column("TwrBsFzt_3"), [-3.0, -3.5])  # the file's own column
    assert np.array_equal(table.column("TwrBsFzt_4"), [-4.0, -4.5])
    assert table.unit("TwrBsFzt_4") == "kN"
    # The same file through read_table (the CableDyn reader) and a unique file: no warning.
    with pytest.warns(UserWarning, match="TwrBsFzt_2"):
        assert read_table(path).channels == table.channels
    unique = tmp_path / "unique.out"
    unique.write_text(OPENFAST_TEXT, encoding="utf-8")
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        read_openfast_output(unique)


