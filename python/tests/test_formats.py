def _outb_header(file_id: int, channels: int, samples: int, *, name_length: int = 10) -> bytes:
    """A binary header, one scale/offset pair, and one short name pair; no data."""
    parts = [struct.pack("<h", file_id)]
    if file_id == 4:
        parts.append(struct.pack("<h", name_length))
    parts.append(struct.pack("<ii", channels, samples))
    parts.append(struct.pack("<dd", 1.0 if file_id == 1 else 0.0, 0.1))
    if file_id != 3:
        parts.append(struct.pack("<ff", 1.0, 0.0))
    parts.append(struct.pack("<i", 0))
    parts.append(b"Time      Chan1     (s)       (-)       ")
    return b"".join(parts)


@pytest.mark.parametrize(
    ("file_id", "channels", "samples", "name_length"),
    [
        (2, 1, 300_000_000, 10),
        (1, 1, 2**31 - 1, 10),
        (3, 2**31 - 1, 1, 10),
        (3, 1, 2**31 - 1, 10),
        (4, 1, 1, 32767),
        (4, 65535, 65535, 2),
    ],
)
def test_openfast_binary_declared_sizes_are_checked_before_allocating(
    tmp_path, file_id, channels, samples, name_length
):
    path = tmp_path / "huge.outb"
    path.write_bytes(_outb_header(file_id, channels, samples, name_length=name_length))
    tracemalloc.start()
    start = perf_counter()
    try:
        with pytest.raises(OutputFormatError, match="truncated: the header declares"):
            read_openfast_output(path)
        elapsed = perf_counter() - start
        peak = tracemalloc.get_traced_memory()[1]
    finally:
        tracemalloc.stop()
    assert elapsed < 5.0
    assert peak < 16 * 2**20


def test_openfast_binary_non_finite_or_overflowing_time_factors_fail_closed(
    tmp_path, binary_series
):
    time, data = binary_series
    path = tmp_path / "time.outb"
    _write_outb(path, 2, time, data, ["Time", "A", "B"], ["(s)", "(m)", "(N)"])
    raw = bytearray(path.read_bytes())
    raw[10:18] = struct.pack("<d", float("inf"))
    path.write_bytes(bytes(raw))
    with pytest.raises(OutputFormatError, match="time scale and offset must be finite"):
        read_openfast_output(path)
    raw[10:26] = struct.pack("<dd", 1.0e308, 1.0e308)
    path.write_bytes(bytes(raw))
    with warnings.catch_warnings():
        warnings.simplefilter("error")
        with pytest.raises(OutputFormatError, match="values must be finite"):
            read_openfast_output(path)


