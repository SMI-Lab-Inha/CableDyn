def _moordyn_line(nodes: int = 3, *, extra: str = "", drop: str | None = None) -> str:
    names = ["Time"]
    units = ["(s)"]
    for node in range(nodes):
        for axis in "xyz":
            names.append(f"Node{node}p{axis}")
            units.append("(m)")
    for segment in range(1, nodes):
        names.append(f"Seg{segment}Ten")
        units.append("(N)")
    if extra:
        names.append(extra)
        units.append("(-)")
    if drop is not None:
        index = names.index(drop)
        del names[index], units[index]
    rows = []
    for step in range(3):
        row = [0.5 * step]
        for node in range(nodes):
            row.extend([10.0 * node + step, 0.0, -50.0 + 10.0 * node])
        row.extend(1.0e5 + 10.0 * segment + step for segment in range(1, nodes))
        if extra:
            row.append(1.0)
        if drop is not None:
            del row[index]
        rows.append("  ".join(f"{value: .7E}" for value in row))
    return "  ".join(names) + "\n" + "  ".join(units) + "\n" + "\n".join(rows) + "\n"


def _write_outb(
    path: Path,
    file_id: int,
    time: np.ndarray,
    data: np.ndarray,
    names: list[str],
    units: list[str],
    *,
    name_length: int = 10,
    trailing: bytes = b"",
    description: str = "Synthetic binary",
) -> None:
    """Write an OpenFAST binary file following NWTC_IO WrBinFAST."""
    samples, channels = data.shape
    parts = [struct.pack("<h", file_id)]
    if file_id == 4:
        parts.append(struct.pack("<h", name_length))
    parts.append(struct.pack("<ii", channels, samples))
    if file_id == 1:
        time_scale, time_offset = 1.0e4, 0.0
        parts.append(struct.pack("<dd", time_scale, time_offset))
    else:
        parts.append(struct.pack("<dd", time[0], time[1] - time[0]))
    if file_id != 3:
        low, high = data.min(axis=0), data.max(axis=0)
        span = np.where(high > low, high - low, 1.0)
        scale = (65535.0 / span).astype(np.float32)
        offset = (-32768.0 - low * scale).astype(np.float32)
        parts.append(scale.tobytes())
        parts.append(offset.tobytes())
    encoded = description.encode("latin-1")
    parts.append(struct.pack("<i", len(encoded)))
    parts.append(encoded)
    for text in [*names, *units]:
        parts.append(text.ljust(name_length)[:name_length].encode("latin-1"))
    if file_id == 1:
        parts.append(np.round(time * time_scale + time_offset).astype("<i4").tobytes())
    if file_id == 3:
        parts.append(data.astype("<f8").tobytes())
    else:
        packed = np.clip(np.round(data * scale + offset), -32768, 32767).astype("<i2")
        parts.append(packed.tobytes())
    path.write_bytes(b"".join(parts) + trailing)


