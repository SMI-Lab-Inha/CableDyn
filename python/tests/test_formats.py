@pytest.mark.parametrize("file_id", [1, 2, 3, 4])
def test_openfast_binary_formats_decode_to_the_written_series(tmp_path, binary_series, file_id):
    time, data = binary_series
    path = tmp_path / "run.outb"
    _write_outb(
        path,
        file_id,
        time,
        data,
        ["Time", "Wave1Elev", "FairTen1"],
        ["(s)", "(m)", "(N)"],
        name_length=12 if file_id == 4 else 10,
    )
    table = read_openfast_output(path)
    assert table.channels == ("Time", "Wave1Elev", "FairTen1")
    assert table.units == ("(s)", "(m)", "(N)")
    assert table.title == "Synthetic binary"
    assert np.allclose(table.time, time, atol=1.0e-9)
    # int16 packing keeps each channel to 1/65535 of its range; float64 is exact.
    tolerance = 0.0 if file_id == 3 else 1.0 / 65535.0
    for index, channel in enumerate(("Wave1Elev", "FairTen1")):
        span = float(np.ptp(data[:, index]))
        assert np.max(np.abs(table.column(channel) - data[:, index])) <= tolerance * span + 1e-12
    assert type(read_table(path)) is TimeHistory


