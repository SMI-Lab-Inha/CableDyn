def test_openfast_binary_keeps_repeated_names_and_rejects_zero_scales(tmp_path, binary_series):
    time, data = binary_series
    path = tmp_path / "dup.outb"
    _write_outb(path, 3, time, data, ["Time", "A", "A"], ["(s)", "(m)", "(m)"])
    with pytest.warns(UserWarning, match=r"A -> A_2"):
        table = read_openfast_output(path)
    assert table.channels == ("Time", "A", "A_2")
    assert np.array_equal(table.column("A"), data[:, 0])
    assert np.array_equal(table.column("A_2"), data[:, 1])
    _write_outb(path, 2, time, data, ["Time", "A", ""], ["(s)", "(m)", "(m)"])
    with pytest.raises(OutputFormatError, match="non-empty"):
        read_openfast_output(path)
    _write_outb(path, 2, time, data, ["Time", "A", "B"], ["(s)", "(m)", "(N)"])
    raw = bytearray(path.read_bytes())
    raw[2 + 8 + 16 : 2 + 8 + 16 + 4] = struct.pack("<f", 0.0)
    path.write_bytes(bytes(raw))
    with pytest.raises(OutputFormatError, match="scale factors"):
        read_openfast_output(path)
    _write_outb(path, 1, time, data, ["Time", "A", "B"], ["(s)", "(m)", "(N)"])
    raw = bytearray(path.read_bytes())
    raw[10:18] = struct.pack("<d", 0.0)
    path.write_bytes(bytes(raw))
    with pytest.raises(OutputFormatError, match="time scale"):
        read_openfast_output(path)


