def test_moordyn_line_file_positions_and_tensions(tmp_path):
    path = tmp_path / "run.MD.Line1.out"
    path.write_text(_moordyn_line(), encoding="utf-8")
    line = read_moordyn_line(path)
    assert isinstance(line, MoorDynLineHistory)
    assert isinstance(read_table(path), MoorDynLineHistory)
    assert line.quantities == ("p", "Ten")
    assert (line.node_count, line.segment_count) == (3, 2)
    xyz = line.positions(0.25)
    assert xyz.shape == (3, 3)
    assert np.allclose(xyz[:, 0], [0.5, 10.5, 20.5])
    assert not xyz.flags.writeable
    assert np.allclose(line.segment_tensions(0.5), [1.0e5 + 11.0, 1.0e5 + 21.0])
    with pytest.raises(KeyError, match="'v' node channels"):
        line.node_vectors("v", 0.0)
    with pytest.raises(KeyError, match="'Str' segment"):
        line.segment_values("Str", 0.0)
    with pytest.raises(ValueError, match="unknown MoorDyn node vector"):
        line.node_vectors("q", 0.0)
    with pytest.raises(ValueError, match="unknown MoorDyn segment"):
        line.segment_values("Force", 0.0)
    trimmed = line.period(0.5, 1.0)
    assert isinstance(trimmed, MoorDynLineHistory)
    assert trimmed.segment_count == 2


